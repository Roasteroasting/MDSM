    public static void Draw(SpriteBatch sprites, Texture2D pixel, string text, int x, int y, int scale, Color color)
    {
        int lineStart = x;
        foreach (char character in text)
        {
            if (character == '\n') { x = lineStart; y += 10 * scale; continue; }
            if (character == '\r') continue;
            char upper = char.ToUpperInvariant(character);
            if (upper != ' ')
            {
                if (!Glyphs.TryGetValue(upper, out string glyph)) glyph = Glyphs['?'];
                for (int row = 0; row < 7; row++)
                for (int column = 0; column < 5; column++)
                    if (glyph[row * 6 + column] == '1')
                        sprites.Draw(pixel, new Rectangle(x + column * scale, y + row * scale, scale, scale), color);
            }
            x += 6 * scale;
        }
    }

    public static string Fit(string text, int maxCharacters) => text.Length <= maxCharacters
        ? text : text[..Math.Max(0, maxCharacters - 3)] + "...";
